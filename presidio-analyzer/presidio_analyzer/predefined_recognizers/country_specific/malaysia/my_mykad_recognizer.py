import calendar
from datetime import date
from typing import List, Optional, Tuple

from presidio_analyzer import Pattern, PatternRecognizer


class MyMykadRecognizer(PatternRecognizer):
    """
    Recognize Malaysia National Registration Identity Card numbers
    (MyKad numbers).

    The number printed on the MyKad (Kad Pengenalan Malaysia) is a
    12-digit number with three parts, written with or without
    hyphens as YYMMDD-PB-###G:

    - Digits 1 to 6: the date of birth as YYMMDD.
    - Digits 7 and 8: the place of birth code (PB), taken from the
      birth certificate on application, for example 01 for Johor,
      07 for Penang and 14 for Kuala Lumpur. Codes 71 and 72 were
      used for people born abroad before 2001, and 88 and 99 are
      assigned to police and armed forces personnel during service.
    - Digits 9 to 11: a serial number generated by the National
      Registration Department computer system.
    - Digit 12: the gender digit, odd for men and even for women.

    Checksum note: the MyKad number has no checksum. Microsoft
    Learn's Malaysia identity card entity definition states the
    checksum explicitly as "No", and the published structure
    sources agree the last four digits are a serial number plus
    the gender digit, not a check value, so this recognizer
    implements no checksum and deliberately does not promote
    matches on an unverified one. Invalidation is based on
    structural sanity checks instead: the value must be exactly
    12 digits once hyphens are removed, the date part must decode
    to a real calendar date that is not in the future (with the
    two-digit year mapped to the 1900s when it is greater than
    the current two-digit year and to the 2000s otherwise), the
    place of birth code must not be 00, the serial plus gender
    part must not be 0000, and trivial numbers such as
    all-same-digit or fully sequential digit runs are rejected.
    This follows the approach of the Pakistani CNIC, Saudi
    national ID, UAE Emirates ID, Egyptian national ID,
    Bangladesh NID, Sri Lanka NIC, Ghana Card, Kazakhstan IIN,
    Ukraine RNOKPP, Uzbekistan PINFL, Morocco CNIE and Indonesia
    NIK recognizers.

    :param patterns: List of patterns to be used by this recognizer
    :param context: List of context words to increase confidence in detection
    :param supported_language: Language this recognizer supports
    :param supported_entity: The entity this recognizer can detect
    :param replacement_pairs: List of tuples with potential replacement values
    for different strings to be used during pattern matching.
    This can allow a greater variety in input, for example by removing dashes or spaces.
    """

    COUNTRY_CODE = "my"

    PATTERNS = [
        Pattern(
            "MY_MYKAD",
            r"(?<![A-Za-z0-9-])\d{6}-?\d{2}-?\d{4}(?![A-Za-z0-9-])",
            0.5,
        ),
    ]

    CONTEXT = [
        "malaysia",
        "malaysian",
        "mykad",
        "kad pengenalan",
        "nric",
        "national registration identity card",
        "identity card",
        "ic number",
    ]

    def __init__(
        self,
        patterns: Optional[List[Pattern]] = None,
        context: Optional[List[str]] = None,
        supported_language: str = "en",
        supported_entity: str = "MY_MYKAD",
        replacement_pairs: Optional[List[Tuple[str, str]]] = None,
        name: Optional[str] = None,
    ) -> None:
        patterns = patterns if patterns else self.PATTERNS
        context = context if context else self.CONTEXT
        super().__init__(
            supported_entity=supported_entity,
            patterns=patterns,
            context=context,
            supported_language=supported_language,
            name=name,
        )

    def invalidate_result(self, pattern_text: str) -> bool:
        """
        Check if the pattern text cannot be an MY_MYKAD entity.

        No checksum exists for this recognizer (see the class
        docstring), so invalidation is based on sanity checks: the
        value must be exactly 12 digits once hyphens are removed,
        the date part must decode to a real calendar date that is
        not in the future, the place of birth code must not be 00,
        the serial plus gender part must not be 0000, and trivial
        numbers such as all-same-digit or fully sequential digit
        runs are rejected.

        :param pattern_text: Text detected as pattern by regex
        :return: True if invalidated
        """
        text = pattern_text.strip().replace("-", "")
        if len(text) != 12 or not text.isdigit():
            return True
        if len(set(text)) == 1:
            # cannot be all the same digit
            return True
        if self._is_sequential(text):
            # a real issued MyKad number is never one fully sequential run
            return True
        if text[6:8] == "00":
            return True
        if text[8:] == "0000":
            return True
        return self._birth_date_is_invalid(text[0:6])

    @staticmethod
    def _birth_date_is_invalid(date_part: str) -> bool:
        """
        Check the YYMMDD birth date part of a MyKad number.

        The two-digit year maps to the 1900s when it is greater
        than the current two-digit year and to the 2000s otherwise.
        The decoded date must be a real calendar date (leap-aware)
        and must not be in the future.

        :param date_part: Six digits, YYMMDD
        :return: True if the date part cannot be a real past birth date
        """
        year_two_digits = int(date_part[0:2])
        month = int(date_part[2:4])
        day = int(date_part[4:6])
        if not 1 <= month <= 12:
            return True
        current_two_digits = date.today().year % 100
        if year_two_digits > current_two_digits:
            year = 1900 + year_two_digits
        else:
            year = 2000 + year_two_digits
        if day < 1 or day > calendar.monthrange(year, month)[1]:
            return True
        try:
            birth_date = date(year, month, day)
        except ValueError:
            return True
        return birth_date > date.today()

    @staticmethod
    def _is_sequential(digits: str) -> bool:
        """
        Check if the digits form a sequential run, allowing 9 to wrap to 0.

        For example, 123456789012 ascends by one each step, and
        654321098765 descends by one each step.

        :param digits: Numeric string to check
        :return: True if every digit follows the previous one sequentially
        """
        values = [int(digit) for digit in digits]
        ascending = all(
            (values[i] + 1) % 10 == values[i + 1] for i in range(len(values) - 1)
        )
        descending = all(
            (values[i] - 1) % 10 == values[i + 1] for i in range(len(values) - 1)
        )
        return ascending or descending

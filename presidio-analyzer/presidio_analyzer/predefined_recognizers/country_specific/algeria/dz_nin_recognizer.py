import datetime
from typing import List, Optional, Tuple

from presidio_analyzer import Pattern, PatternRecognizer


class DzNinRecognizer(PatternRecognizer):
    """
    Recognize Algerian national identification numbers (NIN).

    The NIN (Numero d'Identification Nationale,
    national identification number) is the 18 digit
    personal number assigned to Algerian citizens
    and to foreigners born in Algeria. It is the
    national identification number printed on the
    biometric national identity card (CNIBE), on
    the biometric passport, and on the birth
    certificate (form S12). It is instituted by
    decret executif 23-316 of 6 September 2023
    (Journal officiel n 60 of 13 September 2023),
    article 6, which restates the structure of
    the earlier decret 10-210 of 16 September
    2010.

    The number has 18 digits in six parts: two
    digits carrying the indications relative to
    the sex, to the mention of the act (bis, ter,
    quater or presumed), and to birth in Algeria
    or abroad; three digits, the last three digits
    of the year of registration in the birth
    register; four digits, the code of the commune
    or country of registration of the birth; five
    digits, the birth act number; two digits, the
    register serial number per year; and two
    digits, the control key. It is written plain,
    18 digits with no separators, for example
    100041601000010147.

    Registration year: the three digit year is
    read as 2000 to 2026 when it starts with 0
    (004 is 2004, 026 is 2026) and as 1900 to
    1999 when it starts with 9 (983 is 1983,
    995 is 1995). This is the reading used by
    the dz-nin-checker package for its first
    digits 0 and 9. Any other first digit has
    no plausible reading as the registration
    year of a living holder: 027 to 099 would
    be 2027 to 2099, in the future, or 1027 to
    1099, and 100 to 899 would be 1100 to 1899
    or 2100 to 2899. Registration years in the
    1800s (800 to 899) are not accepted here:
    a person registered in 1899 would be 127
    years old, so no living holder carries
    one.

    Commune code: the four digit block is the
    official commune code (wilaya plus commune)
    for births registered in Algeria, or a
    country code for births registered abroad.
    Verified commune codes, checked against
    the syscli-algeria commune data through
    dz-format: 1601 Alger-centre, 1602 Sidi
    M'Hamed, 1603 El Madania, 1609 Bir Mourad
    Rais, 3101 Oran, 0901 Blida, 2301 Annaba,
    0601 Bejaia, 1501 Tizi Ouzou, 0101 Adrar,
    3501 Boumerdes, 1101 Tamenghasset. Only
    the value 0000 is rejected here, because
    no commune or country carries that code;
    the country codes for births abroad are
    not published, so no wilaya range is
    enforced and foreign-born holders are not
    excluded.

    Control key: there is no published check
    digit formula for the NIN, so none is
    implemented here. Decret 23-316, article
    6, says the contents of the positions are
    detailed by arrete of the minister in
    charge of the interior, and article 7
    creates an automated system to generate
    the NIN; article 2 defines the control
    key as a special number generated by the
    automated system, used to confirm the
    accuracy of the NIN. The dz-format package
    (PyPI, sources listed at
    https://github.com/syscli/dz-format/blob/main/sources/README.md)
    states the same: the key is generated by
    the automated system and its formula is
    not published, so only the length is
    checked. Python-stdnum has no NIN module
    at all (its dz package holds only the tax
    number NIF, checked by length only), and
    the idnumbers library has no DZA module.

    One community package disagrees. The
    dz-nin-checker npm package (version 1.0.4,
    4 stars) claims a modified Luhn key over
    the first 16 digits and splits the first
    two digits as nationality (1 Algerian, 2
    dual nationality) and sex (0 male, 1
    female). Neither claim is in the decree:
    the decree lists no nationality among the
    contents of the first two positions, and
    it says the key is generated by the
    automated system, not by Luhn. The package
    cites no source for either claim, and its
    tests validate only numbers it generated
    itself; no real issued NIN is used as a
    test vector anywhere in that repository.
    Its Luhn key is also a single digit zero
    padded to two digits, so every key it
    generates lies between 00 and 09: if that
    rule were the official one, 90 percent of
    the two digit key space (10 to 99) would
    never occur in a genuine NIN. This
    recognizer does not implement that key:
    enforcing an unverified rule would reject
    genuine numbers. The disagreement was
    measured, not assumed: the recognizer's
    Luhn reimplementation matches the npm
    package on 2000 random 16 digit bodies
    (0 mismatches), and the npm package
    rejects all fifteen test fixtures,
    because their keys are arbitrary two
    digit values rather than its Luhn digit. In a run of
    200,000 random 18 digit tokens, the Luhn
    rule alone passes 2,013 (about 1 in 99);
    249 tokens pass both the Luhn rule and
    this recognizer's structural rules,
    24,885 pass only the structural rules,
    and 1,764 pass only the Luhn rule.

    Seven honest caveats. First, without a
    check digit the structural rules are weak
    evidence on their own: a random 18 digit
    token passes the full validation about
    1 time in 8 (25,134 in 200,000 random
    tokens measured), so the recognizer keeps
    the pattern score at 0.5 and never
    promotes it; the registration year rule
    does almost all of the filtering. Second,
    the values of the first two digit code
    (sex, act mention, birth in Algeria or
    abroad) are not published, so they are
    not restricted here; any two digits are
    accepted. Third, the commune or country
    block is only checked against 0000, so a
    token with a made up commune code still
    passes. Fourth, the zero blocks are
    assumptions, not published rules: the
    birth act number is taken to start at 1,
    so 00000 is rejected, and the register
    serial is taken to start at 01, so 00 is
    rejected; no source confirms either, and
    a genuinely issued number carrying one
    would be missed here, in the safe
    direction. Fifth, the decree defines two
    further NIN layouts that are not matched
    here: foreigners living in Algeria (a 3
    digit special number, a 13 digit
    sequential registration number, and the
    2 digit key) and legal persons (a 1 digit
    special number, a 2 digit demembrement
    number, a 13 digit fiscal identification,
    and the 2 digit key), because neither
    layout publishes segment ranges to
    validate against. Sixth, registration
    years in the 1800s are not accepted, as
    above. Seventh, every all same digit
    string is rejected here as implausible,
    and no fully sequential 18 digit run
    passes validation (all 20 wrap runs
    checked). A passing validation only shows
    the number is well formed; it cannot show
    the number was ever issued to anyone, and
    only the Algerian civil register can
    confirm that.

    The recognizer validates the structure in
    invalidate_result and keeps the pattern
    score at 0.5: it does not promote a match
    to 1.0, because there is no check digit
    and a random same-shape token passes the
    structural rules about 1 time in 8.

    Invalidation is based on: the number must
    be exactly 18 digits; the number must not
    be all the same digit; a fully sequential
    digit run is rejected; the three digit
    registration year must read as 2000 to
    the current year (first digit 0) or 1900
    to 1999 (first digit 9); the commune or
    country code must not be 0000; the birth
    act number must not be 00000; and the
    register serial must not be 00. This
    follows the approach of the Pakistani
    CNIC, Saudi national ID, UAE Emirates ID,
    Egyptian national ID, Bangladesh NID, Sri
    Lanka NIC, Ghana Card, Kazakhstan IIN,
    Ukraine RNOKPP, Uzbekistan PINFL, Morocco
    CNIE, Indonesia NIK, Malaysia MyKad,
    Vietnam CCCD, Chile RUT, Ecuador Cedula,
    Iran Code Melli, Argentina CUIT/CUIL,
    Mexico CURP, Peru RUC, Colombia NIT,
    Dominican Republic Cedula, Paraguay RUC,
    Uruguay RUT, Iceland kennitala, Czech
    birth number, Romanian personal numeric
    code, Dutch citizen service number,
    Croatian personal identification number,
    Slovenian unique master citizen number,
    Bulgarian uniform civil number, Greek tax
    identification number, Serbian unique
    master citizen number, Lithuanian personal
    code, Estonian personal identification
    code, Latvian personal code, and Slovak
    birth number recognizers.

    :param patterns: List of patterns to be used by this recognizer
    :param context: List of context words to increase confidence in detection
    :param supported_language: Language this recognizer supports
    :param supported_entity: The entity this recognizer can detect
    :param replacement_pairs: List of tuples with potential replacement values
    for different strings to be used during pattern matching.
    This can allow a greater variety in input, for example by removing dashes or spaces.
    """

    COUNTRY_CODE = "dz"

    PATTERNS = [
        Pattern(
            "DZ_NIN",
            r"(?<![A-Za-z0-9./-])\d{18}(?![A-Za-z0-9/-])",
            0.5,
        ),
    ]

    CONTEXT = [
        "algeria",
        "algerian",
        "algérie",
        "nin",
        "numéro d'identification nationale",
        "numero d'identification nationale",
        "numéro d'identification national",
        "national identification number",
    ]

    def __init__(
        self,
        patterns: Optional[List[Pattern]] = None,
        context: Optional[List[str]] = None,
        supported_language: str = "en",
        supported_entity: str = "DZ_NIN",
        replacement_pairs: Optional[List[Tuple[str, str]]] = None,
        name: Optional[str] = None,
    ) -> None:
        patterns = patterns if patterns else self.PATTERNS
        context = context if context else self.CONTEXT
        super().__init__(
            supported_entity=supported_entity,
            patterns=patterns,
            context=context,
            supported_language=supported_language,
            name=name,
        )

    def invalidate_result(self, pattern_text: str) -> bool:
        """
        Check if the pattern text cannot be a DZ_NIN entity.

        The number must be 18 digits, must not be all
        the same digit, must not be a fully sequential
        digit run, must carry a plausible registration
        year, a non-zero commune or country code, a
        non-zero birth act number, and a non-zero
        register serial. There is no check digit to
        validate: the control key formula is not
        published.

        :param pattern_text: Text detected as pattern by regex
        :return: True if invalidated
        """
        text = pattern_text.strip()
        if len(text) != 18 or not text.isdigit():
            return True
        if len(set(text)) == 1:
            # cannot be all the same digit
            return True
        if self._is_sequential(text):
            # a real issued number is never one fully sequential run
            return True
        if not self._has_valid_registration_year(text):
            return True
        if text[5:9] == "0000":
            # no commune or country carries the code 0000
            return True
        if text[9:14] == "00000":
            # birth act numbers start at 1
            return True
        if text[14:16] == "00":
            # register serials start at 01
            return True
        return False

    @staticmethod
    def _has_valid_registration_year(digits: str) -> bool:
        """
        Check the registration year encoded in digits 3 to 5.

        The three digit year reads as 2000 to the
        current year when it starts with 0, and as
        1900 to 1999 when it starts with 9. Any other
        first digit has no plausible reading as the
        registration year of a living holder.

        :param digits: The 18 digit national identification number
        :return: True when the encoded registration year is plausible
        """
        year = digits[2:5]
        if year[0] == "0":
            return int(year) <= datetime.date.today().year % 1000
        if year[0] == "9":
            return True
        return False

    @staticmethod
    def _is_sequential(digits: str) -> bool:
        """
        Check if the digits form a sequential run, allowing 9 to wrap to 0.

        For example, 012345678901234567 ascends by one each step, and
        987654321098765432 descends by one each step.

        :param digits: Numeric string to check
        :return: True if every digit follows the previous one sequentially
        """
        values = [int(digit) for digit in digits]
        ascending = all(
            (values[i] + 1) % 10 == values[i + 1] for i in range(len(values) - 1)
        )
        descending = all(
            (values[i] - 1) % 10 == values[i + 1] for i in range(len(values) - 1)
        )
        return ascending or descending
